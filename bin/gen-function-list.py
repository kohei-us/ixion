"""Generate the list of supported formula functions as an rst page.

The page content comes from the specs file given as the argument, normally
misc/function-specs.yaml, which is the single source of truth for what the
page says.  Keep it in step with the sources by hand: when a function gets
implemented, mark it implemented in the specs and run

    bin/gen-function-list.py misc/function-specs.yaml -o doc/functions.rst
"""

import argparse
import sys
import textwrap
from pathlib import Path

import yaml

# Categories in the order they appear on the page, keyed by the category
# names used in the specs.  Functions in a category not listed here are left
# out; this excludes the development helpers.
CATEGORIES = {
    "mathematical": "Mathematical",
    "statistical": "Statistical",
    "logical": "Logical",
    "information": "Information",
    "text": "Text",
    "time": "Date and time",
    "spreadsheet": "Spreadsheet",
}

KNOWN_KEYS = {"category", "implemented", "params", "return", "note", "volatile"}


def check_specs(specs):
    """Check the specs for mistakes and return the errors found."""
    errors = []
    for name, spec in sorted(specs.items()):
        if "implemented" not in spec:
            errors.append(f"{name.upper()} does not say whether it is implemented")
        elif spec["implemented"] and "category" not in spec:
            errors.append(f"{name.upper()} is implemented but has no category")
        for key in sorted(set(spec) - KNOWN_KEYS):
            errors.append(f"{name.upper()} has an unknown key '{key}'")

    return errors


def describe_params(params):
    if params is None:
        return ""

    low = params.get("min")
    high = params.get("max")
    if low is None and high is None:
        return "any number"
    if low is None:
        return f"up to {high}"
    if high is None:
        return f"{low} or more"
    if low == high:
        return str(low)

    return f"{low} to {high}"


def write_page(specs, out):
    listed = {
        name: spec for name, spec in specs.items()
        if spec.get("implemented") and spec.get("category") in CATEGORIES
    }
    unimplemented = [name for name, spec in specs.items() if not spec.get("implemented")]

    out.write(textwrap.dedent(f"""\
        .. This file is generated by bin/gen-function-list.py from
           misc/function-specs.yaml.  Do not edit it by hand.

        .. _functions:

        Supported functions
        ===================

        Ixion implements the {len(listed)} functions listed below, grouped by
        category.  A function marked *volatile* gets re-calculated on every
        calculation, whether or not any cell it references has changed.

        The parser also recognizes the names of {len(unimplemented)} other functions
        that are not implemented yet.  A formula using one of them parses, but
        yields the ``#NAME?`` error when calculated.
        """))

    for key, title in CATEGORIES.items():
        names = sorted(name for name, spec in listed.items() if spec["category"] == key)
        if not names:
            continue

        out.write(textwrap.dedent(f"""\

            {title}
            {"-" * len(title)}

            .. list-table::
               :header-rows: 1
               :widths: auto

               * - Function
                 - Arguments
                 - Returns
                 - Notes
            """))

        for name in names:
            spec = listed[name]
            notes = []
            if spec.get("volatile"):
                notes.append("Volatile.")
            note = spec.get("note")
            if note:
                notes.append(" ".join(str(note).split()))

            row = [
                f"* - ``{name.upper()}``",
                f"  - {describe_params(spec.get('params'))}",
                f"  - {spec.get('return', '')}",
                f"  - {' '.join(notes)}",
            ]
            # an empty cell must not leave trailing whitespace behind
            for line in row:
                out.write(f"   {line.rstrip()}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("specs", type=Path, help="function specs file (yaml)")
    parser.add_argument(
        "--output", "-o", type=argparse.FileType("w"), default=sys.stdout,
        help="file to write the page to (default: standard output)")
    args = parser.parse_args()

    with args.specs.open() as f:
        specs = yaml.safe_load(f)

    # make sure the specs are in good shape
    errors = check_specs(specs)
    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        sys.exit(1)

    write_page(specs, args.output)


if __name__ == "__main__":
    main()
